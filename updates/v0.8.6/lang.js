const normalize = value => value.replace(/\s+/g, ' ').trim();
const originals = new Map();
const attributes = new Map();
const attributeNames = ['alt', 'aria-label', 'placeholder', 'title'];
const attrSelector = '[alt],[aria-label],[placeholder],[title],meta[name="description"],meta[property="og:title"],meta[property="og:description"]';

function collect() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.parentElement || node.parentElement.closest('script,style,noscript,template,svg')) continue;
    const source = node.nodeValue;
    if (strings.has(normalize(source))) originals.set(node, source);
  }
  for (const element of document.querySelectorAll(attrSelector)) {
    const saved = new Map();
    for (const name of attributeNames) {
      const source = element.getAttribute(name);
      if (source !== null && strings.has(normalize(source))) saved.set(name, source);
    }
    if (element.matches('meta[name="description"],meta[property="og:title"],meta[property="og:description"]')) {
      const source = element.getAttribute('content');
      if (source !== null && strings.has(normalize(source))) saved.set('content', source);
    }
    if (saved.size) attributes.set(element, saved);
  }
}

